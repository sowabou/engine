    # Quick smoke test when run directly
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(__file__))))
    setts = parse_all_mail_folders(os.path.join(here, "data", "settlements"))
    print(f"Parsed {len(setts)} unique Ria SWIFT settlements")
    if setts:
        total_eur = sum(s.amount_foreign for s in setts)
        print(f"  Date range: {setts[0].date} → {setts[-1].date}")
        print(f"  Total EUR : {total_eur:,.2f}")
        print(f"  Total MRU : {sum(s.amount_mru for s in setts):,.2f}")
